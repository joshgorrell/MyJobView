import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL('../../' + path, import.meta.url), 'utf8');
const viewer = read('supabase/functions/view-shared-proposal/index.ts');
const manager = read('supabase/functions/manage-proposal-share-link/index.ts');
const builder = read('src/components/Proposals/ProposalBuilderCompact.tsx');
const settings = read('src/components/Proposals/ProposalSettings.tsx');
const modal = read('src/components/Proposals/PreSendValidationModal.tsx');
assert.match(viewer, /proposal\.expires_at/);
assert.match(viewer, /!proposal\.expires_at/);
assert.match(viewer, /Date\.now\(\)\s*>=\s*Date\.parse\(proposal\.expires_at\)/);
assert.match(viewer, /proposal\.sent_at/);
assert.match(viewer, /revoked_at/);
assert.match(manager, /onConflict:\s*'proposal_id'/);
assert.match(manager, /proposal-share:v1:/);
assert.match(manager, /crypto\.randomUUID\(\)/);
assert.match(builder, /\.select\('proposal_approval_days'\)/);
assert.match(builder, /expires_at:\s*expiresAt\.toISOString\(\)/);
assert.match(builder, /sent_at:\s*new Date\(\)\.toISOString\(\)/);
assert.match(settings, /profile\?\.role === 'admin'/);
assert.match(settings, /proposal_approval_days:\s*dealerApprovalDays/);
assert.doesNotMatch(modal, /APPROVAL_WINDOWS/);
console.log('Proposal sharing and unified deadline source-contract checks passed. These do not replace authenticated browser tests.');
