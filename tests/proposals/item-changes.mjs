import assert from 'node:assert/strict';
import { build } from 'esbuild';
const { outputFiles } = await build({ entryPoints: ['src/components/Proposals/proposalItemChanges.ts'], bundle: true, platform: 'node', format: 'esm', write: false });
const { proposalItemChanges, proposalItemUpdate } = await import('data:text/javascript;base64,' + Buffer.from(outputFiles[0].text).toString('base64'));
const before = { unitPrice: 100, quantity: 2, laborHours: 1, laborRate: 80, isCustomerSupplied: false };
const changes = proposalItemChanges(before, { ...before, unitPrice: 125 });
assert.deepEqual(changes, { unit_price: 125 });
const matching = { quantity: 5, unit_price: 100, cost: 50, labor_hours: 2, labor_rate: 90, is_customer_supplied: false };
assert.deepEqual(proposalItemUpdate(matching, changes), { unit_price: 125, line_total: 625, labor_total: 900 });
assert.deepEqual(proposalItemChanges(before, before), {});
assert.equal(proposalItemUpdate(matching, { quantity: 3, labor_hours: 4 }).labor_total, 1080);
assert.deepEqual(proposalItemUpdate(matching, { is_customer_supplied: true }), { is_customer_supplied: true, unit_price: 0, cost: 0, line_total: 0, labor_total: 900 });
console.log('Changed fields only; matching quantities and labor preserved; totals and customer-supplied treatment pass');

const roomAndDiscount = { room_id: 'kitchen', unit_price: 60 };
const selectedUpdate = proposalItemUpdate({ ...matching, quantity: 2, room_id: 'living' }, roomAndDiscount, true);
const otherUpdate = proposalItemUpdate({ ...matching, room_id: 'bedroom' }, roomAndDiscount, false);
assert.equal(selectedUpdate.room_id, 'kitchen');
assert.equal(selectedUpdate.unit_price, 60);
assert.equal(selectedUpdate.line_total, 120);
assert.equal(otherUpdate.room_id, undefined);
assert.equal(otherUpdate.unit_price, 60);
assert.equal(otherUpdate.line_total, 300);
assert.equal(otherUpdate.quantity, undefined);
console.log('Room correction stays local while the $40 discount applies to matching items');
const { proposalSubstitutionUpdate } = await import('data:text/javascript;base64,' + Buffer.from(outputFiles[0].text).toString('base64'));
const newModel = { id: 'new-model', name: 'New speaker', sku: 'NEW', unit_price: 60, cost: 0, default_labor_hours: 0, labor_rate: 90 };
const substitution = proposalSubstitutionUpdate({ ...matching, room_id: 'bedroom', quantity: 5 }, newModel);
assert.equal(substitution.product_id, 'new-model');
assert.equal(substitution.unit_price, 60);
assert.equal(substitution.cost, 0);
assert.equal(substitution.labor_hours, 0);
assert.equal(substitution.line_total, 300);
assert.equal(substitution.labor_total, 0);
assert.equal(substitution.room_id, undefined);
assert.equal(substitution.quantity, undefined);
assert.equal(substitution.parent_item_id, undefined);
assert.equal(proposalSubstitutionUpdate({ ...matching, quantity: 2 }, newModel).line_total, 120);
console.log('Substitutions preserve room, quantity, accessory relationship, and accept zero cost/labor defaults');
