import assert from 'node:assert/strict';
import { reconcileCommittedEquipmentAdditions as reconcile } from '../../supabase/functions/_shared/change-order-equipment-reconciliation.mjs';
const id='11111111-1111-4111-8111-111111111111';
const base={lineId:id,action:'add',productId:'speaker',quantity:4,unitPriceCents:25000};
const changed={...base,quantity:6};
let r=reconcile({committed:[base],staged:[changed]});
assert.equal(r.totalDeltaCents,'50000');
assert.equal(r.effects[0].quantityDelta,2);
assert.equal(r.effects[0].newQuantity,6);
assert.equal(reconcile({committed:[changed],staged:[changed]}).changed,false);
r=reconcile({committed:[base],staged:[{...base,unitPriceCents:30000}]});
assert.equal(r.totalDeltaCents,'20000');
assert.equal(r.effects[0].quantityDelta,0);
assert.equal(reconcile({committed:[base],staged:[]}).totalDeltaCents,'-100000');
assert.equal(reconcile({committed:[],staged:[base]}).totalDeltaCents,'100000');
assert.equal(reconcile({committed:[],staged:[]}).totalDeltaCents,'0');
assert.throws(()=>reconcile({committed:[base,base],staged:[]}),/duplicate/);
assert.throws(()=>reconcile({committed:[base],staged:[{...base,productId:'other'}]}),/identity/);
assert.throws(()=>reconcile({committed:[],staged:[{...base,quantity:1.5}]}),/quantity/);
assert.throws(()=>reconcile({committed:[],staged:[{...base,action:'modify_price'}]}),/only stable addition/);
const max={...base,quantity:Number.MAX_SAFE_INTEGER,unitPriceCents:Number.MAX_SAFE_INTEGER};
assert.equal(reconcile({committed:[],staged:[max]}).totalDeltaCents,(BigInt(max.quantity)*BigInt(max.unitPriceCents)).toString());
console.log('Committed equipment reconciliation tests passed');
