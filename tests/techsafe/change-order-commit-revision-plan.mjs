import assert from 'node:assert/strict';
import { planCommittedChangeOrderRevision as plan } from '../../supabase/functions/_shared/change-order-commit-revision-plan.mjs';
const id = '11111111-1111-4111-8111-111111111111';
const base = { lineId:id, action:'add', productId:'speaker-catalog-id', quantity:4, unitPriceCents:25000 };
const args = { committed:[base], staged:[{...base, quantity:6}], approved:true, expectedRevision:1 };
const p=plan(args);
assert.equal(p.changed,true);
assert.equal(p.nextRevision,2);
assert.deepEqual(p.changes,[{type:'replace',before:base,after:{...base,quantity:6}}]);
assert.equal(plan({...args,committed:args.staged}).changed,false);
assert.deepEqual(plan({...args,staged:[]}).changes,[{type:'reverse',before:base}]);
assert.deepEqual(plan({...args,committed:[],staged:[base]}).changes,[{type:'apply',after:base}]);
assert.deepEqual(plan({...args,staged:[{...base,unitPriceCents:30000}]}).changes[0].after.unitPriceCents,30000);
assert.throws(()=>plan({...args,approved:false}),/approval/);
assert.throws(()=>plan({...args,staged:[base,base]}),/duplicate/);
assert.throws(()=>plan({...args,staged:[{...base,productId:'different'}]}),/identity/);
assert.throws(()=>plan({...args,staged:[{...base,quantity:1.5}]}),/quantity/);
assert.throws(()=>plan({...args,staged:[{...base,action:'modify_labor'}]}),/unsupported/);
console.log('Committed change-order revision preview tests passed');
