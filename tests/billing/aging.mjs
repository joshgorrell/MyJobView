import assert from 'node:assert/strict';
import { calculateInvoiceAging as aging } from '../../src/lib/invoiceAging.ts';
const row={organizationId:'d',id:'a',status:'submitted',balanceCents:100,dueDate:'2026-11-28'};
const dates=['2026-11-28','2026-10-29','2026-10-28','2026-09-29','2026-09-28','2026-08-30','2026-08-29',null];
const invoices=dates.map((dueDate,i)=>({...row,id:String(i),dueDate}));
assert.deepEqual(aging('d',invoices,'2026-11-28'),{current:100,days1To30:100,days31To60:200,days61To90:200,daysOver90:100,unknownDueDate:100,total:800});
assert.equal(aging('d',[{...row,status:'draft'}],'2026-11-28').total,0);
assert.equal(aging('d',[{...row,status:'paid'}],'2026-11-28').total,0);
assert.throws(()=>aging('d',[row,row],'2026-11-28'));
assert.throws(()=>aging('d',[{...row,organizationId:'other'}],'2026-11-28'));
assert.throws(()=>aging('d',[{...row,dueDate:'2026-02-30'}],'2026-11-28'));
console.log('Invoice aging tests passed');
