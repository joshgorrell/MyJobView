// Read-only certificate/freshness gate for a future trusted server transaction.
// No caller-supplied JSON is authority: both rows MUST be fetched independently
// by the server with connection/ledger/certificate locks in one DB transaction.
// Even a passing result cannot authorize dispatch until that adapter exists.
import {compareSalesOrderEquipmentEvidence} from './canonicalEquipmentEvidence.mjs';
const held=reason=>({ok:false,authorized:false,snapshotReady:false,reason});
const id=x=>typeof x==='string'&&/^[A-Za-z0-9_-]{1,128}$/.test(x);
const positive=x=>Number.isSafeInteger(x)&&x>0;
const hash=x=>typeof x==='string'&&/^[0-9a-f]{64}$/.test(x)&&x!=='0'.repeat(64);
const eq=(a,b)=>a===b;
/**
 * Pure validation of independently server-loaded records.
 * Do not expose this as an RPC or call it with browser/client-controlled rows.
 */
export function checkPersistedEquipmentCertificate({connection,ledger,certificate,freshEvidence,lastDelivered}={}) {
  if(!connection||!ledger||!certificate||!freshEvidence) return held('certificate_or_source_missing');
  if(!id(connection.connectionId)||!id(connection.salesOrderId)||!id(connection.organizationId)||
     !id(connection.proposalId)||!positive(connection.generation))
    return held('invalid_connection_identity');
  if(connection.active!==true||connection.enabled!==true) return held('connection_inactive');
  const scope=[['connectionId',connection.connectionId],['orderId',connection.salesOrderId],
    ['organizationId',connection.organizationId],['proposalId',connection.proposalId]];
  for(const [field,value] of scope) {
    if(!eq(certificate[field],value)||!eq(freshEvidence[field],value)) return held('certificate_scope_mismatch');
  }
  if(!eq(ledger.connectionId,connection.connectionId)||
     !eq(ledger.orderId,connection.salesOrderId)||
     !eq(ledger.organizationId,connection.organizationId)||
     !eq(ledger.proposalId,connection.proposalId))
    return held('ledger_scope_mismatch');
  if(!positive(ledger.generation)||!positive(ledger.revision)||
     ledger.generation!==connection.generation||ledger.state!=='candidate')
    return held('ledger_not_current_candidate');
  if(!hash(ledger.fingerprint)||!hash(certificate.fingerprint)||!hash(freshEvidence.fingerprint))
    return held('invalid_fingerprint');
  if(!positive(certificate.generation)||!positive(certificate.revision)||
     certificate.generation!==ledger.generation||certificate.revision!==ledger.revision||
     freshEvidence.connectionGeneration!==ledger.generation||freshEvidence.revision!==ledger.revision)
    return held('certificate_revision_mismatch');
  if(certificate.state!=='certified'||certificate.sourceCommitted!==true||
     certificate.approvalVerified!==true||certificate.transactionVerified!==true)
    return held('certificate_not_committed');
  if(certificate.fingerprint!==ledger.fingerprint||
     freshEvidence.fingerprint!==certificate.fingerprint)
    return held('certificate_source_changed');
  if(freshEvidence.ok!==true||freshEvidence.authorized!==false||
     freshEvidence.snapshotReady!==false)
    return held('invalid_fresh_evidence');
  if(lastDelivered!==null&&lastDelivered!==undefined) {
    if(!id(lastDelivered.connectionId)||!id(lastDelivered.orderId)||
       lastDelivered.connectionId!==connection.connectionId||
       lastDelivered.orderId!==connection.salesOrderId||
       !positive(lastDelivered.generation)||!positive(lastDelivered.revision)||
       !hash(lastDelivered.fingerprint)) return held('invalid_delivery_history');
    if(ledger.generation<lastDelivered.generation||
       (ledger.generation===lastDelivered.generation&&ledger.revision<lastDelivered.revision))
      return held('delivery_revision_rollback');
    if(ledger.generation===lastDelivered.generation&&ledger.revision===lastDelivered.revision&&
       certificate.fingerprint!==lastDelivered.fingerprint)
      return held('delivery_revision_conflict');
  }
  // This is only a comparison contract, not evidence that any DB lock was
  // actually held or that the certificate was generated by trusted SQL.
  return {ok:true,authorized:false,snapshotReady:false,reason:'certificate_matches_not_dispatch_authorized',
    revision:ledger.revision,generation:ledger.generation,fingerprint:certificate.fingerprint};
}
